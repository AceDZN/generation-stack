export type CountryId = keyof typeof COUNTRIES;

export function country(id: CountryId): CountryData {
  return COUNTRIES[id];
}

/** Split `total` blocks over `weights` by largest remainder (ties to the lower band). */
export function apportion(weights: number[], total: number): number[] {
  const sw = weights.reduce((a, b) => a + b, 0);
  const raw = weights.map((w) => (sw > 0 ? (w / sw) * total : 0));
  const out = raw.map(Math.floor);
  let left = total - out.reduce((a, b) => a + b, 0);
  const order = raw.map((r, i) => [r - Math.floor(r), i] as const).sort((a, b) => b[0] - a[0] || a[1] - b[1]);
  for (const [, i] of order) {
    if (left <= 0) break;
    out[i]++;
    left--;
  }
  return out;
}

/**
 * The tower at the start of the decade that begins in `year`: the year's real pyramid,
 * moved up one floor because during the decade everyone gets ten years older (the 0–9s
 * of `year` are the 10–19 floor by the decade's end). The nursery is empty: this decade's
 * babies arrive from Shula. The old 60–69 and 70+ share the top floor.
 */
export function startTower(id: CountryId, year: number, blocks: number): number[] {
  const s = (COUNTRIES[id].shares as Record<number, number[]>)[year];
  if (!s) throw new Error(`no WPP shares for ${id} ${year}`);
  const w = [0, s[0], s[1], s[2], s[3], s[4], s[5], s[6] + s[7]];
  return noFloatingFloors(apportion(w, blocks));
}

/**
 * Rounding can leave a lone block on a top floor above an empty one (a young country's
 * single 60+ block over zero 50–59s). A floor can't float, so that block moves down into
 * the empty floor. Only ever moves one block per gap, and only at the top of the tower.
 */
export function noFloatingFloors(start: number[]): number[] {
  const out = start.slice();
  for (let b = 2; b < out.length; b++) {
    if (out[b] > 0) continue;
    let top = -1;
    for (let k = out.length - 1; k > b; k--) if (out[k] > 0) { top = k; break; }
    if (top < 0) break;
    out[top]--;
    out[b]++;
  }
  return out;
}

/** The real band shares in `year` (for the ghost silhouette). */
export function silhouette(id: CountryId, year: number): number[] {
  const s = (COUNTRIES[id].shares as Record<number, number[]>)[year];
  if (!s) throw new Error(`no WPP shares for ${id} ${year}`);
  return s.slice(0, BAND_COUNT);
}

/** WPP decade means rounded to whole numbers per 1,000, for the mayor's board. */
export function rates(id: CountryId, decade: number): { cbr: number; cdr: number; stage: 1 | 2 | 3 | 4 } {
  const d = (COUNTRIES[id].decades as Record<number, DecadeRates>)[decade];
  if (!d) throw new Error(`no WPP rates for ${id} ${decade}s`);
  const cbr = Math.round(d.cbr);
  const cdr = Math.round(d.cdr);
  return { cbr, cdr, stage: stageOf(cbr, cdr) };
}

/** Blocks a decade's net migration adds to a tower of `blocks` (net per 1,000 per year × 10 years). */
export function netMigrationBlocks(id: CountryId, decade: number, blocks: number): number {
  const d = (COUNTRIES[id].decades as Record<number, DecadeRates>)[decade];
  return Math.round(((d?.net ?? 0) * 10 * blocks) / 1000);
}

/** People one block stands for, rounded to a friendly number. */
export function peoplePerBlock(id: CountryId, year: number, blocks: number): number {
  const m = (COUNTRIES[id].popMillions as Record<number, number>)[year];
  const raw = (m * 1e6) / blocks;
  const mag = 10 ** Math.floor(Math.log10(raw));
  return Math.round(raw / mag) * mag;
}
