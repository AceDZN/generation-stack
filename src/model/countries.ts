/**
 * Workbook's stage rule (BirthDeathBalanceLab classifyStage, matching the
 * demographic-processes stage table): both high = 1, high births = 2, falling births = 3,
 * both low = 4.
 */
export function stageOf(cbr: number, cdr: number): 1 | 2 | 3 | 4 {
  if (cbr >= 30 && cdr >= 28) return 1;
  if (cbr >= 30) return 2;
  if (cbr >= 15) return 3;
  return 4;
}

