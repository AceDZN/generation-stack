// Real country numbers the levels are built on. Pure data + helpers, no Three.js.
//
// Source: United Nations, World Population Prospects 2024 (WPP 2024), estimates
// 1950–2023 and the medium-variant projection from 2024, as processed and published by
// Our World in Data (grapher datasets "population-by-five-year-age-group",
// "crude-birth-rate", "crude-death-rate", "population-growth-rate-with-and-without-migration",
// "births-and-deaths-projected-to-2100", "population-with-un-projections"; downloaded
// 1 November 2026; OWID metadata: "UN, World Population Prospects (2024) – processed by
// Our World in Data", last updated 2024-07-12).
//
// Rounding:
// - shares[year] = the population's share in each ten-year band 0–9 … 60–69, 70+ on
//   1 January-ish of that year (WPP's 1 July estimate), from the 5-year groups summed in
//   pairs and rounded to 3 decimals. Each row sums to 1 ± 0.002.
// - decades[y] = the mean of the ten annual rates y … y+9, per 1,000 people per year,
//   rounded to 0.1. `net` is the mean crude net-migration rate (WPP growth rate minus the
//   rate of natural change). `projected` decades (2020 on) are WPP 2024 medium variant:
//   births / population and deaths / population each year.
// - Levels round these again to whole numbers for the mayor's board.
//
// Where Workbook quotes its own rounded "today" numbers (Niger 45/9, Israel 19/5,
// Germany 9/12, Japan 7/12 — the BirthDeathBalanceLab and PopulationGrowthEngineLab
// presets and the demographic-processes module) the levels that are "today" use
// Workbook's numbers (WORKBOOK below), so the game and the module agree.

